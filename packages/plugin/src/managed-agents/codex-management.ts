import { randomUUID } from 'node:crypto'
import { AsyncLocalStorage } from 'node:async_hooks'
import type { CodexAppServerLike } from '../codex/app-server.js'
import type { ManagedManagementOperation, ManagedManagementRequest } from './management.js'
import type { ManagedAgentEmit } from './types.js'

export const object = (value: unknown): Record<string, unknown> => value !== null && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : {}
const string = (value: unknown, field: string): string => {
  if (typeof value !== 'string' || !value.trim() || value.length > 16_384) throw new Error(`Invalid ${field}.`)
  return value
}
const requirements: Partial<Record<ManagedManagementOperation, string[]>> = {
  state: ['thread/read'], accountUsage: ['account/rateLimits/read'], commands: ['skills/list'],
  compact: ['thread/compact/start', 'thread/backgroundTerminals/list'], rewind: ['thread/read', 'thread/turns/list', 'thread/revert'],
  fork: ['thread/read', 'thread/turns/list', 'thread/fork'], rename: ['thread/name/set'],
  'goal.read': ['thread/goal/get'], 'goal.set': ['thread/goal/get', 'thread/goal/set', 'thread/settings/update'], 'goal.clear': ['thread/goal/clear'],
  'mcp.list': ['mcpServerStatus/list'], 'mcp.reload': ['config/mcpServer/reload'],
  'mcp.reconnect': ['config/mcpServer/reload'], 'mcp.toggle': ['config/read', 'config/batchWrite'],
  'mcp.authenticate': ['mcpServer/oauth/login'], 'mcp.callback': ['mcpServer/oauth/login'],
  'tasks.list': ['thread/backgroundTerminals/list'], 'tasks.stop': ['thread/backgroundTerminals/list', 'thread/backgroundTerminals/terminate'],
}
export interface CodexManagementHost {
  threadId: string
  cwd: string
  client: CodexAppServerLike
  emit: ManagedAgentEmit
  active(): boolean
  ended(): boolean
  settings(): Record<string, unknown>
  permissionConfirmed(): boolean
  /** From a schema generated by THIS executable; absence means unknown. */
  restoredChildren?: ReadonlyArray<{ id: string; parentThreadId: string; title: string; status: string; turnId?: string }>
  supportedMethods?: ReadonlySet<string>
}

export class CodexManagement {
  private readonly callScope = new AsyncLocalStorage<{ dispatched: boolean }>()
  private readonly supported: Set<string>
  private readonly settingsListeners = new Set<() => void>()
  private readonly denied = new Set<string>()
  private context: unknown = null
  private applied: Record<string, unknown> = {}
  private readonly mutations = new Map<string, { operation: string; result?: unknown; unknown: boolean }>()
  private readonly pendingQuestions = new Map<string, { rpcId: string | number; ids: string[] }>()
  private readonly children = new Map<string, { id: string; kind: 'subagent'; title: string; status: string; parentThreadId: string; turnId?: string }>()
  ownsChild(threadId: string): boolean { return this.children.has(threadId) }
  private login?: { server: string; redirect: URL; state: string | null; expires: number }
  constructor(private readonly host: CodexManagementHost) {
    this.supported = new Set(host.supportedMethods)
    const pending = [...(host.restoredChildren ?? [])].slice(0, 1024)
    for (let progress = true; progress;) {
      progress = false
      for (const child of pending) {
        if (!child.id || child.id === host.threadId || this.children.has(child.id) || child.id === child.parentThreadId) continue
        if (child.parentThreadId !== host.threadId && !this.children.has(child.parentThreadId)) continue
        this.children.set(child.id, { ...child, kind: 'subagent', status: 'unknown', turnId: undefined })
        progress = true
      }
    }
  }

  get operations(): ManagedManagementOperation[] {
    return ['context', 'settings', 'question.answer', ...Object.entries(requirements)
      .filter(([operation, methods]) => (operation !== 'goal.set' || this.host.permissionConfirmed()) && methods!.every(method => this.supported.has(method) && !this.denied.has(method)))
      .map(([operation]) => operation as ManagedManagementOperation)]
  }
  observe(method: string, params: Record<string, unknown>): void {
    const carrying = params.threadId
    if (typeof carrying !== 'string' || (carrying !== this.host.threadId && !this.children.has(carrying))) {
      if (method === 'account/rateLimits/updated') this.host.emit({ type: 'account-usage', data: params.rateLimits })
      return
    }
    if (method === 'item/started' || method === 'item/completed') {
      const item = object(params.item)
      const announced = item.type === 'subAgentActivity' && item.kind === 'started' ? [item.agentThreadId]
        : item.type === 'collabAgentToolCall' && item.tool === 'spawnAgent' && Array.isArray(item.receiverThreadIds) ? item.receiverThreadIds : []
      for (const childId of announced) {
        if (typeof childId !== 'string' || !childId || childId === this.host.threadId || this.children.has(childId)) continue
        if (object(object(item.agentsStates)[childId]).status === 'notFound') continue
        const child = { id: childId, kind: 'subagent' as const, parentThreadId: carrying, title: typeof item.prompt === 'string' ? item.prompt.slice(0, 80) : 'Codex subagent', status: 'unknown' }
        this.children.set(childId, child)
        this.host.emit({ type: 'background-task', data: child })
      }
    }
    if (carrying !== this.host.threadId) {
      const child = this.children.get(carrying)!
      if (method === 'turn/started' && typeof object(params.turn).id === 'string') { child.turnId = object(params.turn).id as string; child.status = 'working' }
      if (method === 'turn/completed' && object(params.turn).id === child.turnId) { child.status = String(object(params.turn).status ?? 'completed'); child.turnId = undefined }
      if (method === 'thread/closed') { child.status = 'closed'; child.turnId = undefined }
      this.host.emit({ type: 'background-task', data: { ...child } })
      return
    }
    if (method === 'thread/tokenUsage/updated') { this.context = params.tokenUsage; this.host.emit({ type: 'context-usage', data: this.context }) }
    if (method === 'account/rateLimits/updated') this.host.emit({ type: 'account-usage', data: params.rateLimits })
    if (method === 'thread/settings/updated') { this.applied = object(params.threadSettings); this.host.emit({ type: 'options', data: this.applied }); for (const listener of this.settingsListeners) listener() }
    if (method === 'thread/goal/updated' || method === 'thread/goal/cleared') this.host.emit({ type: 'thread-goal', data: { ...params, cleared: method.endsWith('/cleared') } })
    if (method === 'thread/compacted') this.host.emit({ type: 'compacted', data: params })
  }
  question(rpcId: string | number, params: Record<string, unknown>): void {
    const questions = Array.isArray(params.questions) ? params.questions : []
    const ids = questions.map(question => string(object(question).id, 'question id'))
    if (!ids.length || ids.length > 32 || new Set(ids).size !== ids.length) throw new Error('Invalid Codex questions.')
    const requestId = randomUUID()
    this.pendingQuestions.set(requestId, { rpcId, ids })
    this.host.emit({ type: 'question', requestId, title: 'Codex needs your input', questions })
  }
  clearQuestions(): void { this.pendingQuestions.clear() }
  close(): void { this.pendingQuestions.clear(); this.login = undefined; for (const listener of this.settingsListeners) listener() }
  private check(): void { if (this.host.ended()) throw new Error('Codex process is unavailable.') }
  private async rpc(method: string, params: unknown): Promise<unknown> {
    this.check()
    try {
      if (!['thread/read', 'thread/turns/list', 'thread/backgroundTerminals/list', 'model/list', 'skills/list', 'account/rateLimits/read', 'thread/goal/get', 'mcpServerStatus/list', 'config/read'].includes(method)) {
        const scope = this.callScope.getStore()
        if (scope) scope.dispatched = true
      }
      const result = await this.host.client.call(method, params)
      this.check()
      this.supported.add(method)
      return result
    } catch (error) {
      if (String(object(error).code) === '-32601' || String(object(error).code) === 'CODEX_METHOD_NOT_FOUND') this.denied.add(method)
      throw error
    }
  }
  async idle(): Promise<'idle' | 'busy' | 'unknown'> {
    if (this.host.ended()) return 'unknown'
    if (this.host.active()) return 'busy'
    try {
      const reply = object(await this.rpc('thread/read', { threadId: this.host.threadId, includeTurns: false }))
      const thread = object(reply.thread)
      if (thread.id !== this.host.threadId) return 'unknown'
      const status = object(thread.status).type
      return status === 'idle' ? 'idle' : status === 'active' ? 'busy' : 'unknown'
    } catch { return 'unknown' }
  }
  private async installGoalSettings(): Promise<void> {
    const choices = this.host.settings()
    if (!this.host.permissionConfirmed()) throw new Error('CODEX_GOAL_PERMISSION_REACQUISITION_REQUIRED')
    const settings = { ...(typeof choices.model === 'string' ? { model: choices.model } : {}), ...(typeof choices.effort === 'string' ? { effort: choices.effort } : {}) }
    let notify: () => void = () => undefined
    let acknowledged = false
    let timer: ReturnType<typeof setTimeout> | undefined
    const changed = new Promise<void>((resolve, reject) => {
      notify = () => {
        if (this.host.ended()) reject(new Error('Codex process is unavailable.'))
        else if (acknowledged && Object.entries(settings).every(([key, value]) => this.applied[key] === value)) resolve()
      }
      timer = setTimeout(() => reject(new Error('CODEX_GOAL_SETTINGS_UNCONFIRMED')), 5000)
      this.settingsListeners.add(notify)
    })
    // Attach rejection immediately; a slow RPC must not cause an unhandled timer rejection.
    void changed.catch(() => undefined)
    try {
      await this.rpc('thread/settings/update', { threadId: this.host.threadId, ...settings })
      acknowledged = true
      notify()
      await changed
    } finally { if (timer) clearTimeout(timer); this.settingsListeners.delete(notify) }
  }
  private async preflight(): Promise<void> {
    if (this.host.active()) throw new Error('MANAGED_SESSION_BUSY')
    const response = object(await this.rpc('thread/read', { threadId: this.host.threadId, includeTurns: false }))
    const thread = object(response.thread)
    if (thread.id !== this.host.threadId || thread.historyMode !== 'paginated') throw new Error('CODEX_PAGINATED_HISTORY_REQUIRED')
    if (object(thread.status).type !== 'idle' || this.host.active()) throw new Error('MANAGED_SESSION_BUSY')
  }
  private async turns(): Promise<string[]> {
    const turns: string[] = []
    let cursor: string | undefined
    const seen = new Set<string>()
    for (let page = 0; page < 100; page++) {
      const response = object(await this.rpc('thread/turns/list', { threadId: this.host.threadId, sortDirection: 'desc', limit: 100, ...(cursor ? { cursor } : {}) }))
      if (!Array.isArray(response.data)) throw new Error('Invalid Codex history page.')
      turns.push(...response.data.map(turn => string(object(turn).id, 'turn id')))
      if (response.nextCursor == null) return turns
      cursor = string(response.nextCursor, 'cursor')
      if (seen.has(cursor)) throw new Error('Invalid Codex history cursor.')
      seen.add(cursor)
    }
    throw new Error('Codex history exceeds the bounded checkpoint scan.')
  }
  private async mutation(operation: string, request: ManagedManagementRequest, body: () => Promise<unknown>): Promise<unknown> {
    const operationId = string(request.operationId, 'operationId')
    const prior = this.mutations.get(operationId)
    if (prior) {
      if (prior.operation !== operation) throw new Error('CODEX_OPERATION_ID_CONFLICT')
      if (prior.unknown) { this.callScope.getStore()!.dispatched = true; throw new Error('CODEX_MUTATION_OUTCOME_UNKNOWN') }
      return prior.result
    }
    const receipt = { operation, unknown: true, result: undefined as unknown }
    this.mutations.set(operationId, receipt)
    // Persisted outer receipts must survive a process restart. No retry here.
    receipt.result = await body()
    receipt.unknown = false
    return receipt.result
  }
  private async terminals(threadId = this.host.threadId): Promise<Record<string, unknown>[]> {
    const result: Record<string, unknown>[] = []
    const seen = new Set<string>()
    let cursor: string | undefined
    for (let page = 0; page < 20; page++) {
      const reply = object(await this.rpc('thread/backgroundTerminals/list', { threadId, ...(cursor ? { cursor } : {}) }))
      if (!Array.isArray(reply.data)) throw new Error('Invalid background terminal list.')
      result.push(...reply.data.map(object).filter(task => task.threadId === undefined || task.threadId === threadId))
      if (reply.nextCursor == null) return result
      cursor = string(reply.nextCursor, 'cursor')
      if (seen.has(cursor)) throw new Error('Invalid background terminal cursor.')
      seen.add(cursor)
    }
    throw new Error('Too many background terminal pages.')
  }
  async manage(operation: ManagedManagementOperation, request: ManagedManagementRequest): Promise<unknown> {
    return this.callScope.run({ dispatched: false }, async () => {
      try { return await this.execute(operation, request) }
      catch (error) {
        const failure = error instanceof Error ? error : new Error('Codex management failed.')
        if (!this.callScope.getStore()?.dispatched) Object.assign(failure, { definiteRejection: true })
        throw failure
      }
    })
  }
  private async refreshChildren(): Promise<void> {
    for (const child of this.children.values()) {
      const response = object(await this.rpc('thread/read', { threadId: child.id, includeTurns: false }))
      const thread = object(response.thread)
      if (thread.id !== child.id) throw new Error('Invalid child thread identity.')
      if (object(thread.status).type === 'idle') { child.status = 'idle'; child.turnId = undefined }
      else if (object(thread.status).type === 'active') {
        child.status = 'unknown'
        const page = object(await this.rpc('thread/turns/list', { threadId: child.id, limit: 1, sortDirection: 'desc' }))
        const turn = object(Array.isArray(page.data) ? page.data[0] : undefined)
        if (typeof turn.id === 'string' && turn.status === 'inProgress') { child.status = 'working'; child.turnId = turn.id }
      }
      this.host.emit({ type: 'background-task', data: { ...child } })
    }
  }
  private async execute(operation: ManagedManagementOperation, request: ManagedManagementRequest): Promise<unknown> {
    this.check()
    if (request.threadId !== undefined && request.threadId !== this.host.threadId) throw new Error('Foreign Codex thread.')
    const threadId = this.host.threadId
    switch (operation) {
      case 'state': {
        const idle = await this.idle()
        const checkpoints = idle === 'idle' && this.supported.has('thread/turns/list')
          ? (await this.turns()).map((turnId, index) => ({ id: turnId, turnId, title: `Turn ${index + 1}` })) : []
        return { idle, providerSessionId: threadId, checkpoints }
      }
      case 'context': {
        const usage = object(this.context)
        const last = object(usage.last)
        const usedTokens = typeof last.totalTokens === 'number' ? last.totalTokens : undefined
        const contextWindow = typeof usage.modelContextWindow === 'number' ? usage.modelContextWindow : undefined
        return { available: this.context !== null, usedTokens, contextWindow,
          ...(usedTokens !== undefined && contextWindow && contextWindow > 0 ? { remainingTokens: Math.max(0, contextWindow - usedTokens), percent: Math.min(100, usedTokens / contextWindow * 100) } : {}) }
      }
      case 'settings': {
        const settings = this.host.settings()
        const catalog = object(await this.rpc('model/list', {}))
        const models = (Array.isArray(catalog.data) ? catalog.data : []).map(object)
        const current = models.find(model => model.model === settings.model || model.id === settings.model)
        return { options: [
          { key: 'model', label: 'Model', value: settings.model, choices: models.map(model => ({ value: model.model ?? model.id, label: model.displayName ?? model.model ?? model.id })) },
          { key: 'reasoningEffort', label: 'Reasoning effort', value: settings.effort, choices: (Array.isArray(current?.supportedReasoningEfforts) ? current.supportedReasoningEfforts : []).map(effort => ({ value: object(effort).reasoningEffort, label: object(effort).description ?? object(effort).reasoningEffort })) },
          { key: 'permissionMode', label: 'Permissions', value: object(settings.sandboxPolicy).type === 'readOnly' ? 'read-only' : object(settings.sandboxPolicy).type === 'dangerFullAccess' ? 'danger-full-access' : 'workspace-write', choices: ['read-only', 'workspace-write', 'danger-full-access'].map(value => ({ value, label: value })) },
        ], applied: this.applied }
      }
      case 'accountUsage': {
        const reply = object(await this.rpc('account/rateLimits/read', {}))
        const buckets = Object.entries(object(reply.rateLimitsByLimitId))
        if (!buckets.length && reply.rateLimits) buckets.push(['codex', reply.rateLimits])
        const windows = buckets.flatMap(([name, bucket]) => ['primary', 'secondary'].flatMap(position => {
          const window = object(object(bucket)[position])
          if (typeof window.usedPercent !== 'number' || !Number.isFinite(window.usedPercent)) return []
          const reset = window.resetsAt
          return [{ name: `${name} · ${position}`, usedPercent: window.usedPercent,
            ...(typeof reset === 'number' && Number.isFinite(reset) && Math.abs(reset * 1000) <= 8.64e15 ? { resetsAt: new Date(reset * 1000).toISOString() } : {}) }]
        }))
        return { windows, ...(windows.length ? {} : { message: 'Account usage is unavailable for this provider.' }) }
      }
      case 'commands': {
        const reply = object(await this.rpc('skills/list', { cwds: [this.host.cwd] }))
        return { commands: (Array.isArray(reply.data) ? reply.data : []).flatMap(entry => {
          const skills = object(entry).skills
          return (Array.isArray(skills) ? skills : []).map(object).filter(skill => typeof skill.name === 'string' && skill.enabled !== false)
            .map(skill => ({ name: skill.name, description: typeof skill.description === 'string' ? skill.description : '' }))
        }) }
      }
      case 'rename': return this.rpc('thread/name/set', { threadId, name: string(request.title, 'title') })
      case 'compact':
        if (request.instructions !== undefined) throw new Error('Codex compact does not accept custom instructions.')
        if (this.host.active()) throw new Error('MANAGED_SESSION_BUSY')
        if ([...this.children.values()].some(child => ['working', 'unknown'].includes(child.status)) || (await this.terminals()).length) throw new Error('CODEX_BACKGROUND_WORK_ACTIVE')
        return this.mutation(operation, request, async () => {
          await this.rpc('thread/compact/start', { threadId })
          return { state: 'accepted' }
        })
      case 'rewind':
      case 'fork': {
        await this.preflight()
        const checkpointId = operation === 'rewind' || request.checkpointId !== undefined
          ? string(request.checkpointId, 'checkpointId') : undefined
        const turns = await this.turns()
        const at = checkpointId ? turns.indexOf(checkpointId) : -1
        if (checkpointId && at < 0) throw new Error('CODEX_INVALID_REWIND_TARGET')
        const target = checkpointId ? { beforeTurnId: checkpointId, keptTurnId: turns[at + 1] ?? null } : undefined
        return this.mutation(operation, request, async () => {
          if (this.host.active()) throw new Error('MANAGED_SESSION_BUSY')
          const response = object(await this.rpc(operation === 'rewind' ? 'thread/revert' : 'thread/fork', {
            threadId, ...(target ? { beforeTurnId: target.beforeTurnId } : {}),
            ...(operation === 'fork' ? { excludeTurns: true, cwd: this.host.cwd } : {}),
          }))
          const id = string(object(response.thread).id, 'provider session id')
          if (operation === 'rewind' ? id !== threadId : id === threadId) throw new Error('Invalid Codex mutation identity.')
          return { state: 'completed', providerSessionId: id, checkpointId, ...target }
        })
      }
      case 'goal.read': return this.rpc('thread/goal/get', { threadId })
      case 'goal.clear': return this.rpc('thread/goal/clear', { threadId, origin: 'user' })
      case 'goal.set': {
        if (request.tokenBudget !== undefined) throw new Error('Codex goal token budget is not supported by this adapter.')
        if (this.host.active()) throw new Error('MANAGED_SESSION_BUSY')
        const status = request.status ?? 'active'
        if (!['active', 'paused'].includes(String(status))) throw new Error('Invalid goal status.')
        const objective = request.objective === undefined ? undefined : string(request.objective, 'objective')
        if (objective && objective.length > 4000) throw new Error('Goal objective exceeds 4000 characters.')
        const previous = object(await this.rpc('thread/goal/get', { threadId })).goal
        if (objective !== undefined && previous != null && object(previous).objective !== objective) throw new Error('Clear the previous goal before replacing it.')
        if (objective === undefined && previous == null) throw new Error('There is no goal to update.')
        // A goal can start work by itself, so its model/permissions must be installed first.
        if (status === 'active') await this.installGoalSettings()
        return this.mutation(operation, request, () => this.rpc('thread/goal/set', { threadId, origin: 'user', status, ...(objective && previous == null ? { objective } : {}) }))
      }
      case 'question.answer': {
        const requestId = string(request.requestId, 'requestId')
        const pending = this.pendingQuestions.get(requestId)
        if (!pending) throw new Error('Question is no longer pending.')
        const raw = object(request.answers)
        if (Object.keys(raw).length !== pending.ids.length || Object.keys(raw).some(key => !pending.ids.includes(key))) throw new Error('Answer every offered question exactly once.')
        const answers: Record<string, { answers: string[] }> = {}
        for (const id of pending.ids) {
          const values = Array.isArray(raw[id]) ? raw[id] as unknown[] : object(raw[id]).answers
          if (!Array.isArray(values) || !values.length || values.some(value => typeof value !== 'string' || value.length > 16_384)) throw new Error('Invalid question answers.')
          answers[id] = { answers: values as string[] }
        }
        this.pendingQuestions.delete(requestId)
        this.callScope.getStore()!.dispatched = true
        await this.host.client.respond(pending.rpcId, { answers })
        return { answered: true }
      }
      case 'tasks.list':
        await this.refreshChildren()
        return { tasks: [...(await this.terminals()).map(task => ({ ...task, id: task.processId, kind: 'terminal', supportsStop: true })), ...[...this.children.values()].map(child => ({ ...child, supportsStop: !!child.turnId }))], supportsBackground: false }
      case 'tasks.stop': {
        const taskId = string(request.taskId ?? request.processId, 'taskId')
        const child = this.children.get(taskId)
        if (child) {
          await this.refreshChildren()
          const owned = new Set([child.id])
          for (let changed = true; changed;) {
            changed = false
            for (const candidate of this.children.values()) {
              if (!owned.has(candidate.id) && owned.has(candidate.parentThreadId)) { owned.add(candidate.id); changed = true }
            }
          }
          let stopped = true
          for (const id of owned) {
            const target = this.children.get(id)!
            const activeTurn = target.turnId
            if (activeTurn) await this.rpc('turn/interrupt', { threadId: id, turnId: activeTurn })
            for (const terminal of await this.terminals(id)) {
              const processId = string(terminal.processId, 'processId')
              await this.rpc('thread/backgroundTerminals/terminate', { threadId: id, processId })
            }
            const status = object(object(await this.rpc('thread/read', { threadId: id, includeTurns: false })).thread)
            if (status.id !== id || object(status.status).type !== 'idle' || (await this.terminals(id)).length) stopped = false
          }
          return { accepted: true, stopped }

        }
        const processId = taskId
        if (!(await this.terminals()).some(task => task.processId === processId)) throw new Error('Background process is not owned by this session.')
        await this.rpc('thread/backgroundTerminals/terminate', { threadId, processId })
        const remaining = await this.terminals()
        return { stopped: !remaining.some(task => task.processId === processId) }
      }
      case 'mcp.list': {
        const items: unknown[] = []
        let cursor: string | undefined
        const seen = new Set<string>()
        for (let page = 0; page < 20; page++) {
          const reply = object(await this.rpc('mcpServerStatus/list', { threadId, detail: 'toolsAndAuthOnly', ...(cursor ? { cursor } : {}) }))
          if (!Array.isArray(reply.data)) throw new Error('Invalid MCP server list.')
          items.push(...reply.data)
          if (reply.nextCursor == null) return { servers: items.map(object).map(server => ({ ...server, status: server.status ?? server.authStatus ?? 'unknown' })) }
          cursor = string(reply.nextCursor, 'cursor')
          if (seen.has(cursor)) throw new Error('Invalid MCP server cursor.')
          seen.add(cursor)
        }
        throw new Error('Too many MCP server pages.')
      }
      case 'mcp.reconnect':
      case 'mcp.reload': return this.rpc('config/mcpServer/reload', undefined)
      case 'mcp.toggle': {
        const name = string(request.name ?? request.server, 'name')
        if (!/^[A-Za-z0-9_-]+$/.test(name) || typeof request.enabled !== 'boolean') throw new Error('Invalid MCP toggle.')
        const config = object(await this.rpc('config/read', { includeLayers: true, cwd: this.host.cwd }))
        const user = (Array.isArray(config.layers) ? config.layers : []).map(object).find(layer => object(layer.name).type === 'user')
        if (!Object.hasOwn(object(object(user?.config).mcp_servers), name)) throw new Error('MCP server is not declared in the user configuration.')
        return this.rpc('config/batchWrite', { edits: [{ keyPath: `mcp_servers.${name}.enabled`, value: request.enabled, mergeStrategy: 'upsert' }], reloadUserConfig: true })
      }
      case 'mcp.authenticate': {
        const name = string(request.name ?? request.server, 'name')
        if (!/^[\w:@/.-]+$/.test(name)) throw new Error('Invalid MCP server.')
        const reply = object(await this.rpc('mcpServer/oauth/login', { name, threadId, timeoutSecs: 300 }))
        const url = new URL(string(reply.authorizationUrl, 'authorizationUrl'))
        if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password) throw new Error('Invalid MCP authorization URL.')
        const redirect = url.searchParams.getAll('redirect_uri')
        this.login = redirect.length === 1 ? { server: name, redirect: new URL(redirect[0]!), state: url.searchParams.get('state'), expires: Date.now() + 300_000 } : undefined
        return { authUrl: url.href }
      }
      case 'mcp.callback': {
        const pending = this.login
        const callback = new URL(string(request.callbackUrl, 'callbackUrl'))
        if (!pending || pending.expires < Date.now() || pending.server !== (request.name ?? request.server) || callback.protocol !== 'http:' || !['127.0.0.1', 'localhost', '[::1]'].includes(callback.hostname) || callback.username || callback.password || callback.origin !== pending.redirect.origin || callback.pathname !== pending.redirect.pathname || (pending.state !== null && callback.searchParams.get('state') !== pending.state)) throw new Error('MCP callback does not match the pending login.')
        this.login = undefined
        this.callScope.getStore()!.dispatched = true
        const response = await fetch(callback, { redirect: 'manual', signal: AbortSignal.timeout(15_000) })
        await response.body?.cancel()
        if (!response.ok) throw new Error('Codex refused the MCP callback.')
        return { completed: true }
      }
      default: throw new Error('MANAGED_OPERATION_UNSUPPORTED')
    }
  }
}
